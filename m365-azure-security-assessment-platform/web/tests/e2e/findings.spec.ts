import { expect } from "@playwright/test";
import { captureLayout, downloadText, navigate, openPreview, tenantA, tenantB, test } from "./helpers";

test("findings filters, scoped detail, keyboard close and safe downloads", async ({ page }, testInfo) => {
  await openPreview(page);
  await navigate(page, "Findings");
  await expect(page.locator("tbody tr")).toHaveCount(13);
  await page.getByLabel("Status filter").selectOption("Noncompliant");
  await expect(page.locator("tbody tr")).toHaveCount(2);
  await page.getByLabel("Search records").fill("EXO-001");
  await expect(page.locator("tbody tr")).toHaveCount(1);
  await page.getByRole("button", { name: "Open EXO-001", exact: true }).focus();
  await page.keyboard.press("Enter");
  const dialog = page.getByRole("dialog");
  await expect(dialog).toContainText("External automatic forwarding");
  await expect(dialog).toContainText(tenantA);
  await expect(dialog).not.toContainText(tenantB);
  await expect(dialog).toContainText("exchange-org-a");
  await expect(dialog).toContainText("Observed fixture value");
  await expect(dialog).toContainText("Expected fixture value");
  await expect(dialog).toContainText("Guidance only");
  await expect(dialog.locator("pre").nth(0)).toContainText('"external_auto_forwarding_allowed": true');
  await expect(dialog.locator("pre").nth(1)).toContainText('"external_auto_forwarding_allowed": false');
  await expect(page.getByRole("button", { name: "Close detail" })).toBeFocused();
  await captureLayout(page, testInfo, "finding-detail");
  for (const key of ["Tab", "Tab", "Tab", "Shift+Tab", "Shift+Tab", "Shift+Tab"]) {
    await page.keyboard.press(key);
    expect(await dialog.evaluate((element) => document.activeElement === document.body || element.contains(document.activeElement)), `${key}: focus must not reach an outside interactive element`).toBe(true);
  }
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Open EXO-001", exact: true })).toBeFocused();
  const exported = JSON.parse(await downloadText(page, testInfo, "JSON"));
  expect(exported.provenance).toMatchObject({ tenantId: tenantA, writesEnabled: false, sourceRevision: "unverified" });
  expect(exported.records).toHaveLength(1);
  expect(exported.records[0]).toMatchObject({ tenantId: tenantA, controlId: "EXO-001" });
  const csv = await downloadText(page, testInfo, "CSV");
  expect(csv).toContain("SYNTHETIC PREVIEW - NOT LIVE EVIDENCE");
  expect(csv).toContain("exchange-org-a");
  expect(csv).not.toContain(tenantB);
  await page.getByLabel("Search records").fill("<script>alert(1)</script>");
  await expect(page.getByRole("heading", { name: "No matching records" })).toBeVisible();
  expect(JSON.parse(await downloadText(page, testInfo, "JSON")).records).toHaveLength(0);
  await page.getByLabel("Customer", { exact: true }).selectOption(tenantB);
  await navigate(page, "Findings");
  await page.getByLabel("Search records").fill("exchange-org-a");
  await expect(page.getByRole("heading", { name: "No matching records" })).toBeVisible();
  await page.getByRole("button", { name: "Clear filters", exact: true }).first().click();
  await page.getByLabel("Search records").fill("EXO-001");
  await page.getByRole("button", { name: "Open EXO-001", exact: true }).click();
  await expect(dialog).toContainText("exchange-org-b");
  await expect(dialog).not.toContainText(tenantA);
});